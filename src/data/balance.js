// 于是「跳过」比认真打完更划算。固定 50 让低血撤退成为一次真实决策：
// 付得起就撤，付不起就战败。
export const SKIP_HP_COST = 50;

// 怪物的蓄力自主攻击（docs/product-backlog.md 清单 13）。三档，键名与
