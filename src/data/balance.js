// 怪物血量的**怪种**分层（与楼层分层互相独立）。
//
// ★ 为什么是「倍率」而不是「加值」：
//   血量的设计单位是「词」—— 一场战斗按 targetWords 折算（hpMax = perWord × 词数 × 倍率）。
//   任何「加 X 点血」的写法在深层会被 perWord 的增长淹没（深层 perWord 已上百，
//   几十点的差别玩家读不出来），在浅层又会把最短的一场压成两三下就死。
//   倍率是**相对**量：它把差异按比例摊到每一场战斗的每一词上，
//   于是「强怪每场多打半词」这件事在 1 层和 9 层一样成立，深度不会让它失效。
// ★ 为什么锚在 mean 而不是锚在最低档（base 3 = 1.0）：
//   锚在最低档等于给 8 种怪**全都**加了血（平均 +28%）—— 那是在偷偷改难度曲线，
//   与「不改难度曲线」的分工冲突。锚在均值让 8 种怪**期望完全不变**：
//   一半怪变软、一半变硬，玩家感知到的方差变大，可预期的难度一点没动。
//   （抽怪是 8 选 1 等概率，所以「按怪种取期望」精确等于「按旧公式取期望」。）
export const FOE_HP_SCALE = {
  mean: 4.75,   // 8 种怪 base 的算术平均；4.75 → 4 档倍率对称分布在 1 两侧
  per: 0.2,     // base 每高 1 档，血量 ×(1+0.2)=+20%
  min: 0.5,     // 夹紧下限：脏数据/越界 base 绝不做成一场打不赢的战斗
  max: 2.0,     // 夹紧上限
};

