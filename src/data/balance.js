//   idleMs      —— 蓄力前站桩多久（玩家有喘息、能读词的窗口）
//   telegraphMs —— 蓄力窗口：这段时间内一次有效字母尝试可打断
//   recoverMs   —— 收招/被打断后的窗口（反打机会）
//   damage      —— 蓄满打出的固定伤害（先护盾后生命）
